"use client";

import { useState } from "react";
import { BarChart3, Download, RefreshCw } from "lucide-react";

const sampleReport = `PROJECT PROGRESS REPORT
Generated by Reporting Agent

Period: November 11-18, 2026

EXECUTIVE SUMMARY
The team completed 14 tasks this week across 5 active projects. Overall project health is good, with the Customer Onboarding Flow project at 85% completion and on track for delivery.

ACTIVE PROJECTS
1. Q4 Marketing Campaign: 65% complete (8/12 tasks done). On track for December 31 deadline.
2. Product Roadmap 2026: 40% complete (8/20 tasks done). Some tasks need attention this week.
3. Customer Onboarding Flow: 85% complete (6/7 tasks done). Nearing completion.
4. Team Knowledge Base: 20% complete (3/15 tasks done). Behind schedule, needs prioritization.
5. Sales Pipeline Optimization: 11% complete (1/9 tasks done). Early stage.

TEAM HIGHLIGHTS
Sarah Chen: 11 tasks completed (highest this week)
James Okoye: 7 tasks completed
Maria Silva: 8 tasks completed

AI AGENT ACTIVITY
Q&A Agent: 28 questions answered this month
Task Routing Agent: 15 routing decisions made
Automation: 47 workflow executions completed

RECOMMENDED ACTIONS
1. Prioritize Team Knowledge Base tasks to improve completion rate
2. Assign additional resources to Product Roadmap 2026
3. Begin planning Customer Onboarding Flow delivery review`;

const reportTypes = [
  { id: "weekly", label: "Weekly Progress Report" },
  { id: "project", label: "Project Status Report" },
  { id: "team", label: "Team Activity Report" },
  { id: "ai", label: "AI Agent Activity Report" },
];

export default function ReportingAgentPage() {
  const [selected, setSelected] = useState("weekly");
  const [report, setReport] = useState(sampleReport);
  const [loading, setLoading] = useState(false);

  async function generate() {
    setLoading(true);
    await new Promise(r => setTimeout(r, 1500));
    setReport(sampleReport);
    setLoading(false);
  }

  return (
    <div className="p-6 lg:p-8">
      <div className="flex items-center justify-between mb-6">
        <div className="flex items-center gap-3">
          <div className="w-9 h-9 bg-green-500 rounded-xl flex items-center justify-center">
            <BarChart3 size={16} className="text-white" />
          </div>
          <div>
            <h1 className="font-manrope font-semibold text-[#171717]">Reporting Agent</h1>
            <div className="flex items-center gap-1.5">
              <div className="w-1.5 h-1.5 bg-green-400 rounded-full"></div>
              <span className="font-inter text-xs text-green-600">Active</span>
            </div>
          </div>
        </div>
        <button className="flex items-center gap-2 text-sm font-inter text-[#777777] border border-[#E8E8E8] px-3 py-2 rounded-lg hover:bg-[#FAFAFA] transition-colors">
          <Download size={14} /> Export
        </button>
      </div>

      <div className="grid lg:grid-cols-4 gap-5">
        <div className="lg:col-span-1">
          <div className="bg-white rounded-2xl border border-[#E8E8E8] p-4">
            <p className="font-inter text-xs font-medium text-[#777777] uppercase tracking-wide mb-3">Report Type</p>
            <div className="space-y-1">
              {reportTypes.map(r => (
                <button
                  key={r.id}
                  onClick={() => setSelected(r.id)}
                  className={`w-full text-left px-3 py-2 rounded-lg text-sm font-inter transition-colors ${selected === r.id ? "bg-[#EAF3FF] text-[#1677E8] font-medium" : "text-[#777777] hover:bg-[#FAFAFA]"}`}
                >
                  {r.label}
                </button>
              ))}
            </div>
            <button
              onClick={generate}
              disabled={loading}
              className="mt-4 w-full flex items-center justify-center gap-2 bg-[#1677E8] text-white font-inter font-medium text-sm py-2.5 rounded-lg hover:bg-[#1265CC] disabled:opacity-60 transition-colors"
            >
              {loading ? <><RefreshCw size={14} className="animate-spin" /> Generating...</> : "Generate Report"}
            </button>
          </div>
        </div>

        <div className="lg:col-span-3 bg-white rounded-2xl border border-[#E8E8E8] p-5">
          <div className="flex items-center justify-between mb-4">
            <p className="font-manrope font-semibold text-[#171717] text-sm">
              {reportTypes.find(r => r.id === selected)?.label}
            </p>
            <span className="font-inter text-xs text-[#777777]">Generated just now</span>
          </div>
          {loading ? (
            <div className="flex items-center justify-center h-48">
              <div className="flex gap-1.5">
                {[0,1,2].map(i => <div key={i} className="w-2 h-2 bg-green-500/40 rounded-full animate-bounce" style={{ animationDelay: `${i * 0.15}s` }}></div>)}
              </div>
            </div>
          ) : (
            <pre className="font-inter text-sm text-[#171717] leading-relaxed whitespace-pre-wrap">{report}</pre>
          )}
        </div>
      </div>
    </div>
  );
}
